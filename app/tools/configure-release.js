// Writes GitHub owner/repo from release.config.json into the updater config and the receipt link base,
// and the public update key from ~/.tauri/tokenstab.key.pub.
const fs = require('fs');
const path = require('path');
const os = require('os');
const root = path.join(__dirname, '..');
const cfg = JSON.parse(fs.readFileSync(path.join(root, 'release.config.json'), 'utf8'));
const pubPath = path.join(os.homedir(), '.tauri', 'tokenstab.key.pub');
const confPath = path.join(root, 'src-tauri', 'tauri.conf.json');
const conf = JSON.parse(fs.readFileSync(confPath, 'utf8'));

conf.bundle.createUpdaterArtifacts = true;
conf.plugins = conf.plugins || {};
conf.plugins.updater = {
  pubkey: fs.existsSync(pubPath) ? fs.readFileSync(pubPath, 'utf8').trim() : '',
  endpoints: [`https://github.com/${cfg.owner}/${cfg.repo}/releases/latest/download/latest.json`],
  windows: { installMode: 'passive' }
};
fs.writeFileSync(confPath, JSON.stringify(conf, null, 2));

const base = `https://${cfg.owner.toLowerCase()}.github.io/${cfg.repo}/r/`;
fs.writeFileSync(path.join(root, 'src', 'release.gen.js'),
  `// GENERATED by tools/configure-release.js — do not edit.\nexport const RECEIPT_BASE = ${JSON.stringify(base)};\nexport const CONFIGURED = ${JSON.stringify(cfg.owner !== 'YOUR_GITHUB_NAME')};\n`);
console.log('release config:', cfg.owner + '/' + cfg.repo, '→', base, conf.plugins.updater.pubkey ? '(pubkey ok)' : '(NO PUBKEY)');
